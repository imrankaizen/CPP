// Print the table of n ; where n is Positive Integer
#include<iostream>
using namespace std;
int main ()
         {
          int i,n; 
          cout << "Enter a Number :- ";
          cin >> n;
          for(i=1; i<=10; i++)
             {
              cout << n << " * " << i << " = " << n*i <<endl; 
             }  
          return 0;  
         }
         