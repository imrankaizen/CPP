// Print Hello World ! n times
#include<iostream>
using namespace std;
int main()
         {
          int n,i; 
          cout << "Enter no. of Iteration :- ";
          cin >> n;
          for(i=1; i<=n; i++) 
             {
              cout << i << " Hello World !" << endl;  
             }   
          return 0; 
         }
          